using System.Reflection;

namespace LocalFileAudit.Core.Common;

/// <summary>
/// Single source of truth for runtime application version.
/// Reads AssemblyInformationalVersion or Assembly Version metadata configured via Directory.Build.props.
/// </summary>
public static class AppVersion
{
    private static readonly Lazy<string> _current = new(() =>
    {
        var appAssembly = Assembly.GetEntryAssembly();
        if (appAssembly == null || !appAssembly.GetName().Name?.StartsWith("LocalFileAudit", StringComparison.OrdinalIgnoreCase) == true)
        {
            appAssembly = typeof(AppVersion).Assembly;
        }

        var infoVersion = appAssembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion;
        if (!string.IsNullOrWhiteSpace(infoVersion))
        {
            // Strip git commit hash suffix if generated by dotnet sdk (e.g. "1.1.0+sha12345")
            var plusIdx = infoVersion.IndexOf('+');
            return plusIdx > 0 ? infoVersion[..plusIdx] : infoVersion;
        }

        var ver = appAssembly.GetName().Version;
        return ver != null ? $"{ver.Major}.{ver.Minor}.{ver.Build}" : "0.0.0-unknown";
    });

    public static string Current => _current.Value;
}
